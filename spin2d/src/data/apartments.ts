// Get min/max values for filters
export const getFilterBounds = (apartments: Apartment[]) => {
  const areas = apartments.map(a => a.area);
  const prices = apartments.map(a => a.price);
  const rooms = apartments.map(a => a.rooms);
  const floors = apartments.map(a => a.floor);

  return {
    area: { min: Math.floor(Math.min(...areas)), max: Math.ceil(Math.max(...areas)) },
    price: { min: Math.floor(Math.min(...prices)), max: Math.ceil(Math.max(...prices)) },
    rooms: { min: Math.min(...rooms), max: Math.max(...rooms) },
    floor: { min: Math.min(...floors), max: Math.max(...floors) },
  };
};

export const filterBounds = getFilterBounds(allApartments);
